#!/usr/bin/env python3
"""Rasterize the licensed DejaVu Sans Mono source for the LVGL code viewer."""
import argparse,hashlib,math
from pathlib import Path
from PIL import ImageFont
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--font',type=Path,default=ROOT/'assets/fonts/DejaVuSansMono.ttf')
p.add_argument('--output',type=Path,default=ROOT/'firmware/components/ui/code_font.c')
args=p.parse_args();font=ImageFont.truetype(str(args.font),14)
points=sorted(set(range(32,127))|set(range(160,256))|set(range(0x2013,0x2020))|{0x3c0,0xfffd})
bitmap=[];rows=[]
for code in points:
    character=chr(code);left,top,right,bottom=font.getbbox(character,anchor='ls')
    mask=font.getmask(character,mode='L');width,height=mask.size
    assert (width,height)==(right-left,bottom-top)
    alpha=[(value*15+127)//255 for value in mask];offset=len(bitmap)
    bitmap += [(alpha[i]<<4)|(alpha[i+1] if i+1<len(alpha) else 0) for i in range(0,len(alpha),2)]
    rows.append(f' {{{code}u,{offset}u,{width},{height},{left},{-bottom}}}')
source='''/* Generated by host/generate_code_font.py. Font data: DejaVu Sans Mono,
 * Bitstream Vera/DejaVu license; see assets/fonts/LICENSE-DejaVu. */
#include "lvgl.h"
typedef struct {uint32_t code,offset;uint8_t width,height;int8_t x,y;} code_glyph;
static const unsigned char pixels[]={\n'''
source+='\n'.join(' '+','.join(str(x) for x in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24))+'\n};\n'
source+='static const code_glyph glyphs[]={\n'+',\n'.join(rows)+'\n};\n'
source+='''static const code_glyph *find(uint32_t c){
 unsigned lo=0,hi=sizeof glyphs/sizeof *glyphs;
 while(lo<hi){unsigned mid=(lo+hi)/2;if(glyphs[mid].code<c)lo=mid+1;else hi=mid;}
 return lo<sizeof glyphs/sizeof *glyphs && glyphs[lo].code==c?&glyphs[lo]:&glyphs[sizeof glyphs/sizeof *glyphs-1];
}
static bool describe(const lv_font_t *font,lv_font_glyph_dsc_t *d,uint32_t c,uint32_t next){
 (void)font;(void)next;const code_glyph *g=find(c);
 d->adv_w=8;d->box_w=g->width;d->box_h=g->height;d->ofs_x=g->x;d->ofs_y=g->y;d->bpp=4;d->is_placeholder=0;return true;
}
static const uint8_t *image(const lv_font_t *font,uint32_t c){(void)font;return pixels+find(c)->offset;}
const lv_font_t sc_code_font={.get_glyph_dsc=describe,.get_glyph_bitmap=image,.line_height=18,.base_line=4};
'''
args.output.write_text(source)
print(f'Generated {len(points)} glyphs, {len(bitmap)} bitmap bytes; font SHA256 {hashlib.sha256(args.font.read_bytes()).hexdigest()}')
